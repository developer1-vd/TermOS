#!/usr/bin/env bash
# build-iso.sh: build the TermOS live ISO.
#
#   sudo iso/build-iso.sh               build on a Fedora host
#   iso/build-iso.sh --container        build inside a Fedora container (podman or docker)
#   iso/build-iso.sh --ks-only          only write build/termos.ks
#
# Environment:
#   TERMOS_RELEASE   Fedora release to base on (default: 45)
#   TERMOS_ARCH      architecture (default: x86_64)
#   TERMOS_DARLING   1 to preinstall Darling for macOS apps (default), 0 to skip
#   TERMOS_ENGINE    --container only: podman or docker (default: podman if installed)
#   TERMOS_WORKDIR   --container only: host directory for the build's scratch
#                    space (/var/tmp in the container), e.g. on a bigger disk
#
# The ISO lands in build/out/. A full build needs ~15 GB of free disk space,
# root, loop devices, and a network connection to the Fedora mirrors.
set -euo pipefail

repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
build="$repo/build"
ks="$build/termos.ks"

die() { echo "build-iso: $*" >&2; exit 1; }

# TermOS's own version (VERSION file), and the Fedora release it's built on.
version="$(tr -d '[:space:]' < "$repo/VERSION")"
release="${TERMOS_RELEASE:-45}"
arch="${TERMOS_ARCH:-x86_64}"
darling="${TERMOS_DARLING:-1}"
[[ "$version" =~ ^[0-9]+(\.[0-9]+)*$ ]] || die "VERSION must look like 0.1, got '$version'"
[[ "$release" =~ ^[0-9]+$ ]] || die "TERMOS_RELEASE must be a Fedora release number, got '$release'"

# Append a heredoc to the kickstart that recreates $src at $dest on the image.
# Text files are copied as-is; binary files (images) are base64-encoded.
embed() {
    local src="$1" dest="$2" mode="$3" tag="TERMOS_EOF_$RANDOM$RANDOM"
    grep -q "^$tag\$" "$src" && die "heredoc tag collision in $src"
    {
        echo "mkdir -p '$(dirname "$dest")'"
        if grep -qI . "$src"; then
            echo "cat > '$dest' <<'$tag'"
            sed -e "s/@@VERSION@@/$version/g" -e "s/@@RELEASE@@/$release/g" "$src"
        else
            echo "base64 -d > '$dest' <<'$tag'"
            base64 -w 76 "$src"
        fi
        echo "$tag"
        echo "chmod $mode '$dest'"
    } >> "$ks"
}

# Embed every file under $1 at the same relative path under $2.
embed_tree() {
    local src_dir="$1" dest_dir="$2" f
    while IFS= read -r f; do
        embed "$src_dir/$f" "$dest_dir/$f" 0644
    done < <(cd "$src_dir" && find . -type f ! -name '*.py' -printf '%P\n' | sort)
}

write_ks() {
    mkdir -p "$build"
    local strip='/^# @@DARLING_BEGIN@@$/,/^# @@DARLING_END@@$/d'
    [[ "$darling" == 0 ]] || strip='/^# @@DARLING_\(BEGIN\|END\)@@$/d'
    sed -e "s/@@RELEASE@@/$release/g" -e "s/@@VERSION@@/$version/g" -e "$strip" \
        "$repo/iso/termos.ks.in" > "$ks"
    # Put our %post first: kickstart runs %post sections in file order, so
    # insert it right before the template's first %post.
    local files_ks="$build/files.ks"
    : > "$files_ks"
    local saved="$ks"; ks="$files_ks"
    {
        echo "# ---- TermOS files (generated by iso/build-iso.sh) ----"
        echo "%post"
    } >> "$ks"
    embed "$repo/bin/termos-fetch"                  /usr/bin/termos-fetch 0755
    embed "$repo/bin/termos-run"                    /usr/bin/termos-run 0755
    embed "$repo/branding/logo-matrix.txt"          /usr/share/termos/logo-matrix.txt 0644
    embed "$repo/branding/logo-termite.txt"         /usr/share/termos/logo-termite.txt 0644
    embed "$repo/config/fastfetch/config.jsonc"     /usr/share/termos/fastfetch/config.jsonc 0644
    embed "$repo/config/neofetch/config.conf"       /usr/share/termos/neofetch/config.conf 0644
    # Wallpaper (desktop + phone sizes), boot splash and KDE defaults.
    embed_tree "$repo/branding/wallpaper"               /usr/share/wallpapers/TermOS
    embed_tree "$repo/branding/plymouth/termos"         /usr/share/plymouth/themes/termos
    embed "$repo/branding/kde/zz-termos-wallpaper.js" \
        /usr/share/plasma/shells/org.kde.plasma.desktop/contents/updates/zz-termos-wallpaper.js 0644
    embed "$repo/branding/kde/kscreenlockerrc"      /etc/xdg/kscreenlockerrc 0644
    # Easter eggs: TermOS fortunes (indexed in %post) and a GRUB command.
    embed "$repo/branding/fortune/termos"           /usr/share/games/fortune/termos 0644
    embed "$repo/branding/grub/42_termos"           /etc/grub.d/42_termos 0755
    # TermOS branding in /etc/os-release (run and enabled by the template's %post).
    embed "$repo/branding/os-release/termos-os-release" /usr/libexec/termos/termos-os-release 0755
    embed "$repo/branding/os-release/termos-os-release.service" \
        /etc/systemd/system/termos-os-release.service 0644
    embed "$repo/branding/os-release/termos-os-release.path" \
        /etc/systemd/system/termos-os-release.path 0644
    # TermOS logo icons (installed over Fedora's logo by the template's %post).
    embed_tree "$repo/branding/icons/hicolor"           /usr/share/termos/icons/hicolor
    embed "$repo/branding/icons/install-icons.sh"   /usr/libexec/termos/install-icons.sh 0755
    # GRUB theme (turned on by the template's %post).
    embed_tree "$repo/branding/grub/termos"             /usr/share/termos/grub/termos
    embed "$repo/branding/grub/install-grub-theme.sh" \
        /usr/libexec/termos/install-grub-theme.sh 0755
    # Live session: an "Install TermOS" icon on the desktop.
    embed "$repo/branding/installer/termos-live-desktop.sh" \
        /usr/libexec/termos/termos-live-desktop.sh 0755
    embed "$repo/branding/installer/termos-live-desktop.desktop" \
        /etc/xdg/autostart/termos-live-desktop.desktop 0644
    echo "%end" >> "$ks"
    ks="$saved"
    awk -v f="$files_ks" '
        !done && /^%post/ { while ((getline l < f) > 0) print l; print ""; done=1 }
        { print }
    ' "$ks" > "$ks.tmp" && mv "$ks.tmp" "$ks"
    rm -f "$files_ks"
    echo "build-iso: wrote $ks (TermOS $version on Fedora $release, Darling: $([[ "$darling" == 0 ]] && echo no || echo yes))"
}

# The ISO's own boot menus come from lorax's live templates. Copy them and
# patch both menus (BIOS and UEFI) to load the TermOS GRUB theme, which
# the kickstart's %post installs at /boot/grub2/themes/termos in the image.
prepare_templates() {
    local src=/usr/share/lorax/templates.d/99-generic
    local dest="$build/lorax-templates"
    [[ -d "$src/live" ]] || die "lorax templates not found at $src"
    rm -rf "$dest"
    cp -r "$src" "$dest"

    local theme_block="$build/theme.cfg"
    cat > "$theme_block" <<'CFG'

# TermOS boot menu theme
if [ -f ($root)/boot/grub2/themes/termos/theme.txt ]; then
  insmod all_video
  insmod gfxterm
  insmod png
  set gfxmode=auto
  terminal_output gfxterm
  for f in ($root)/boot/grub2/themes/termos/*.pf2; do loadfont $f; done
  set theme=($root)/boot/grub2/themes/termos/theme.txt
fi
CFG
    local cfg
    for cfg in "$dest"/live/config_files/x86/grub2-bios.cfg "$dest"/live/config_files/x86/grub2-efi.cfg; do
        grep -q "^search .*@ISOLABEL@" "$cfg" || die "unexpected lorax template: $cfg"
        sed -i "/^search .*@ISOLABEL@/r $theme_block" "$cfg"
        # Menu entries say "Start TermOS 0.1" rather than the Fedora release.
        sed -i "s/@VERSION@/$version/g" "$cfg"
    done
    # Put the theme on the ISO next to the BIOS grub.cfg; UEFI GRUB finds it
    # there too, since both menus search for the ISO by label first.
    # (${GRUB2DIR} is a lorax template variable, so it stays unexpanded.)
    # shellcheck disable=SC2016
    grep -q '^mkdir ${GRUB2DIR}$' "$dest/live/x86.tmpl" || die "unexpected lorax x86.tmpl"
    # shellcheck disable=SC2016
    sed -i 's|^mkdir ${GRUB2DIR}$|mkdir ${GRUB2DIR}\nmkdir ${GRUB2DIR}/themes/termos\ninstall boot/grub2/themes/termos/* ${GRUB2DIR}/themes/termos/|' \
        "$dest/live/x86.tmpl"
    rm -f "$theme_block"
}

build_host() {
    [[ $EUID -eq 0 ]] || die "run as root (sudo), or use --container"
    command -v livemedia-creator >/dev/null || die "install lorax: sudo dnf install lorax anaconda-tui"
    write_ks
    prepare_templates
    rm -rf "$build/out"
    livemedia-creator \
        --ks "$ks" \
        --lorax-templates "$build/lorax-templates" \
        --no-virt \
        --make-iso \
        --iso-only \
        --project TermOS \
        --releasever "$release" \
        --volid "TermOS-$version" \
        --iso-name "TermOS-$version-$arch.iso" \
        --resultdir "$build/out" \
        --logfile "$build/livemedia.log"
    echo "build-iso: done: $build/out/TermOS-$version-$arch.iso"
}

build_container() {
    local engine="${TERMOS_ENGINE:-}" extra=()
    if [[ -z "$engine" ]]; then
        engine="$(command -v podman || command -v docker)" || die "install podman or docker"
    fi
    engine="$(command -v "$engine")" || die "container engine not found: ${TERMOS_ENGINE:-}"
    # Rootless podman can't set up the loop devices the build needs.
    if [[ "$(basename "$engine")" == podman && $EUID -ne 0 ]]; then
        die "podman needs root for this build: use sudo, or TERMOS_ENGINE=docker"
    fi
    if [[ -n "${TERMOS_WORKDIR:-}" ]]; then
        mkdir -p "$TERMOS_WORKDIR"
        extra+=(-v "$TERMOS_WORKDIR:/var/tmp:z")
    fi
    write_ks
    "$engine" run --rm --privileged \
        -v /dev:/dev \
        -v "$repo:/src:z" \
        "${extra[@]}" \
        -e TERMOS_RELEASE="$release" -e TERMOS_ARCH="$arch" -e TERMOS_DARLING="$darling" \
        "registry.fedoraproject.org/fedora:$release" \
        bash -c 'dnf install -y lorax anaconda-tui && /src/iso/build-iso.sh'
}

case "${1:-}" in
    "")           build_host ;;
    --container)  build_container ;;
    --ks-only)    write_ks ;;
    -h|--help)    sed -n '2,15s/^# \{0,1\}//p' "$0" ;;
    *)            die "unknown option: $1 (see --help)" ;;
esac
